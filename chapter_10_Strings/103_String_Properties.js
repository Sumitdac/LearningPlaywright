// String properties & Basic access

let str = "Hello, World!";
// Length
console.log(str.length); // 13

// Access by Index
console.log(str[0]); //H
console.log(str[7]); //W

console.log(str.at(-1)); //!
console.log(str.at(-6)); //W

//charAt()
console.log(str.charAt(0)); //H
//charCodeAt() - Unicode Value
console.log(str.charCodeAt(0)); //72