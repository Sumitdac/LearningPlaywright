//Identifiers, Literal, Operator

var a = 10;

//var - Keyword
//Identifier - Variable name  - a (the name which is given to the container)
//Literal - Variable value -  10 (the value that store in the container )
// = - Operator

//Rule of Identifier:
//1. Must start with a letter, underscore, or dollar sign
//2. Can contain letters, numbers, underscores, and dollar signs
//3. Cannot start with a number
//4. Cannot be a reserved keyword
//5. Cannot contains spaces
//6. Cannot contains special charachters other than underscore and dollar sign
//7. Case sensitive

var name = "Hello";
console.log(name);

var $name = "Hello";
console.log($name);

var _name = "Hello";
console.log(_name);

var name1 = "Hello";
console.log(name1);

var name$1 = "Hello";
console.log(name$1);

var name_1$1 = "Hello";
console.log(name_1$1);

var name_1$1_2 = "Hello";
console.log(name_1$1_2);

