//Comparison operator (Will always result in boolean, true or false)

//>,<,>=,<=,!,!=
console.log(3 > 4); //false
console.log(3 < 4); //true
console.log(4 >= 4); //true
console.log(3 <= 4); //true

console.log(5 == "5"); //true
console.log(5 === "5"); //false

console.log(5 != "5"); //false
console.log(5 !== "5"); //true

//console.log(5 !=== "5"); //This doesn't exist

